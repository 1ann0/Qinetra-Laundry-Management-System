-- Adds per-piece tally exceptions and an immutable clothing-check history.
-- Apply before releasing the matching API and frontend.
BEGIN;

ALTER TABLE order_service_lines
ADD COLUMN IF NOT EXISTS item_checked_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL;

ALTER TABLE order_service_lines
ADD COLUMN IF NOT EXISTS item_checked_by_username VARCHAR(50);

ALTER TABLE order_service_lines
ADD COLUMN IF NOT EXISTS item_checked_at TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS order_service_lines_item_checked_by_id_idx
ON order_service_lines(item_checked_by_id);

CREATE TABLE IF NOT EXISTS order_item_exceptions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id INTEGER NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    description VARCHAR(200),
    is_damaged BOOLEAN NOT NULL DEFAULT FALSE,
    damage_note VARCHAR(300),
    stain_note VARCHAR(300),
    CONSTRAINT order_item_exception_has_detail CHECK (
        description IS NOT NULL
        OR is_damaged
        OR stain_note IS NOT NULL
    ),
    CONSTRAINT order_item_exception_damage_has_note CHECK (
        NOT is_damaged OR damage_note IS NOT NULL
    )
);

CREATE INDEX IF NOT EXISTS order_item_exceptions_order_item_id_idx
ON order_item_exceptions(order_item_id);

CREATE TABLE IF NOT EXISTS order_item_check_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_service_line_id INTEGER NOT NULL REFERENCES order_service_lines(id) ON DELETE CASCADE,
    revision INTEGER NOT NULL,
    check_status VARCHAR(20) NOT NULL,
    item_snapshot JSONB NOT NULL,
    changed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    changed_by_username VARCHAR(50) NOT NULL,
    change_reason VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_item_check_history_line_revision
        UNIQUE (order_service_line_id, revision)
);

CREATE INDEX IF NOT EXISTS order_item_check_history_service_line_id_idx
ON order_item_check_history(order_service_line_id);

CREATE INDEX IF NOT EXISTS order_item_check_history_changed_by_id_idx
ON order_item_check_history(changed_by_id);

ALTER TABLE order_item_exceptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_item_check_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON order_item_exceptions FROM PUBLIC;
REVOKE ALL ON order_item_check_history FROM PUBLIC;

-- Supabase roles may not exist in a plain local PostgreSQL test server.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON order_item_exceptions FROM anon;
        REVOKE ALL ON order_item_check_history FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON order_item_exceptions FROM authenticated;
        REVOKE ALL ON order_item_check_history FROM authenticated;
    END IF;
END $$;

COMMIT;
