-- Private owner preferences; no email delivery or scheduler is enabled by saving.
BEGIN;
CREATE TABLE IF NOT EXISTS alert_settings (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    owner_email VARCHAR(254),
    backup_minute INTEGER NOT NULL DEFAULT 1320 CHECK (backup_minute >= 0 AND backup_minute < 1440),
    revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0),
    updated_at TIMESTAMPTZ
);
INSERT INTO alert_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;
CREATE TABLE IF NOT EXISTS alert_settings_changes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settings_id INTEGER NOT NULL REFERENCES alert_settings(id) ON DELETE RESTRICT,
    before_email VARCHAR(254),
    after_email VARCHAR(254) NOT NULL,
    before_backup_minute INTEGER NOT NULL,
    after_backup_minute INTEGER NOT NULL,
    revision INTEGER NOT NULL,
    request_key VARCHAR(36) UNIQUE NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE alert_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE alert_settings_changes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON alert_settings, alert_settings_changes FROM PUBLIC;
REVOKE ALL ON SEQUENCE alert_settings_changes_id_seq FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
        REVOKE ALL ON alert_settings, alert_settings_changes FROM anon;
        REVOKE ALL ON SEQUENCE alert_settings_changes_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
        REVOKE ALL ON alert_settings, alert_settings_changes FROM authenticated;
        REVOKE ALL ON SEQUENCE alert_settings_changes_id_seq FROM authenticated;
    END IF;
END $$;
COMMIT;
