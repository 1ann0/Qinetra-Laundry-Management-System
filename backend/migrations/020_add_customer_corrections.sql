-- Owner-only contact corrections preserve earlier names and numbers.
BEGIN;

CREATE TABLE IF NOT EXISTS customer_corrections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    before_state JSON NOT NULL,
    after_state JSON NOT NULL,
    reason VARCHAR(300) NOT NULL,
    shared_phone_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    request_key VARCHAR(36) UNIQUE,
    request_hash VARCHAR(64),
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS customer_corrections_customer_id_idx
ON customer_corrections(customer_id);
ALTER TABLE customer_corrections ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON customer_corrections FROM PUBLIC;
REVOKE ALL ON SEQUENCE customer_corrections_id_seq FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON customer_corrections FROM anon;
        REVOKE ALL ON SEQUENCE customer_corrections_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON customer_corrections FROM authenticated;
        REVOKE ALL ON SEQUENCE customer_corrections_id_seq FROM authenticated;
    END IF;
END $$;

COMMIT;
