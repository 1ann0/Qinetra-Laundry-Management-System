-- Records unresolved customer questions that must pause an order.
BEGIN;

CREATE TABLE IF NOT EXISTS order_holds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    hold_type VARCHAR(30) NOT NULL DEFAULT 'customer_reply',
    reason VARCHAR(300) NOT NULL,
    created_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    resolved_by_username VARCHAR(50),
    resolution_note VARCHAR(300),
    resolved_at TIMESTAMPTZ,
    CONSTRAINT order_holds_supported_type CHECK (hold_type = 'customer_reply'),
    CONSTRAINT order_holds_resolution_complete CHECK (
        (resolved_at IS NULL AND resolved_by_username IS NULL AND resolution_note IS NULL)
        OR
        (resolved_at IS NOT NULL AND resolved_by_username IS NOT NULL AND resolution_note IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS order_holds_order_id_idx ON order_holds(order_id);
CREATE INDEX IF NOT EXISTS order_holds_created_by_id_idx ON order_holds(created_by_id);
CREATE INDEX IF NOT EXISTS order_holds_resolved_by_id_idx ON order_holds(resolved_by_id);
CREATE UNIQUE INDEX IF NOT EXISTS order_holds_one_active_customer_reply_idx
ON order_holds(order_id)
WHERE resolved_at IS NULL AND hold_type = 'customer_reply';

ALTER TABLE order_holds ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON order_holds FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON order_holds FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON order_holds FROM authenticated;
    END IF;
END $$;

COMMIT;
