-- Tracks each garment sent to and returned from an outside dry cleaner.
BEGIN;

-- Older service lines keep their history; only new dry-cleaning lines require
-- an explicit handling choice before Ready.
ALTER TABLE order_service_lines
ADD COLUMN IF NOT EXISTS outsourcing_required BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE order_service_lines
ADD COLUMN IF NOT EXISTS in_house_reason VARCHAR(300);
ALTER TABLE order_service_lines
ADD COLUMN IF NOT EXISTS in_house_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE order_service_lines
ADD COLUMN IF NOT EXISTS in_house_by_username VARCHAR(50);
ALTER TABLE order_service_lines
ADD COLUMN IF NOT EXISTS in_house_at TIMESTAMPTZ;

CREATE INDEX IF NOT EXISTS order_service_lines_outsourcing_required_idx
ON order_service_lines(order_id)
WHERE outsourcing_required;

CREATE TABLE IF NOT EXISTS outsource_handovers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_service_line_id INTEGER NOT NULL UNIQUE
        REFERENCES order_service_lines(id) ON DELETE CASCADE,
    partner_name VARCHAR(100) NOT NULL,
    expected_return_at TIMESTAMPTZ NOT NULL,
    sent_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    sent_by_username VARCHAR(50) NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS outsource_handover_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handover_id INTEGER NOT NULL
        REFERENCES outsource_handovers(id) ON DELETE CASCADE,
    order_item_id INTEGER NOT NULL UNIQUE
        REFERENCES order_items(id) ON DELETE RESTRICT,
    garment_reference VARCHAR(50) NOT NULL,
    returned_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    returned_by_username VARCHAR(50),
    returned_at TIMESTAMPTZ,
    return_condition VARCHAR(20),
    issue_note VARCHAR(300),
    issue_resolved_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    issue_resolved_by_username VARCHAR(50),
    issue_resolved_at TIMESTAMPTZ,
    resolution_note VARCHAR(300),
    CONSTRAINT outsource_return_state_complete CHECK (
        (
            returned_at IS NULL
            AND returned_by_username IS NULL
            AND return_condition IS NULL
            AND issue_note IS NULL
        )
        OR
        (
            returned_at IS NOT NULL
            AND returned_by_username IS NOT NULL
            AND return_condition IN ('returned_ok', 'issue')
            AND (
                (return_condition = 'returned_ok' AND issue_note IS NULL)
                OR
                (return_condition = 'issue' AND issue_note IS NOT NULL)
            )
        )
    ),
    CONSTRAINT outsource_issue_resolution_complete CHECK (
        (
            issue_resolved_at IS NULL
            AND issue_resolved_by_username IS NULL
            AND resolution_note IS NULL
        )
        OR
        (
            issue_resolved_at IS NOT NULL
            AND issue_resolved_by_username IS NOT NULL
            AND resolution_note IS NOT NULL
            AND return_condition = 'issue'
        )
    )
);

CREATE INDEX IF NOT EXISTS outsource_handovers_service_line_idx
ON outsource_handovers(order_service_line_id);

CREATE INDEX IF NOT EXISTS outsource_handover_items_handover_idx
ON outsource_handover_items(handover_id);

CREATE INDEX IF NOT EXISTS outsource_handover_items_returned_idx
ON outsource_handover_items(returned_at);

ALTER TABLE outsource_handovers ENABLE ROW LEVEL SECURITY;
ALTER TABLE outsource_handover_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON outsource_handovers, outsource_handover_items FROM PUBLIC;
REVOKE ALL ON SEQUENCE outsource_handovers_id_seq,
    outsource_handover_items_id_seq FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON outsource_handovers, outsource_handover_items FROM anon;
        REVOKE ALL ON SEQUENCE outsource_handovers_id_seq,
            outsource_handover_items_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON outsource_handovers, outsource_handover_items FROM authenticated;
        REVOKE ALL ON SEQUENCE outsource_handovers_id_seq,
            outsource_handover_items_id_seq FROM authenticated;
    END IF;
END $$;

COMMIT;
