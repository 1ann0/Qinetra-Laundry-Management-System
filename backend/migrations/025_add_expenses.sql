-- Owner costs and immutable history; no existing financial records are changed.
BEGIN;
CREATE TABLE IF NOT EXISTS expenses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paid_date DATE NOT NULL,
    category VARCHAR(20) NOT NULL CHECK (category IN ('supplies','utilities','rent','wages','outsourcing','other')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(10) NOT NULL CHECK (payment_method IN ('cash','mpesa')),
    reference VARCHAR(100) NOT NULL DEFAULT '',
    note VARCHAR(1000) NOT NULL DEFAULT '',
    is_voided BOOLEAN NOT NULL DEFAULT FALSE,
    revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0),
    request_key VARCHAR(36) UNIQUE NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_expenses_paid_date ON expenses(paid_date);
CREATE TABLE IF NOT EXISTS expense_changes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id INTEGER NOT NULL REFERENCES expenses(id) ON DELETE RESTRICT,
    before_details JSONB,
    after_details JSONB NOT NULL,
    reason VARCHAR(200) NOT NULL,
    revision INTEGER NOT NULL CHECK (revision >= 0),
    request_key VARCHAR(36) UNIQUE NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT expense_change_revision UNIQUE(expense_id,revision)
);
ALTER TABLE expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE expense_changes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON expenses,expense_changes FROM PUBLIC;
REVOKE ALL ON SEQUENCE expenses_id_seq,expense_changes_id_seq FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
        REVOKE ALL ON expenses,expense_changes FROM anon;
        REVOKE ALL ON SEQUENCE expenses_id_seq,expense_changes_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
        REVOKE ALL ON expenses,expense_changes FROM authenticated;
        REVOKE ALL ON SEQUENCE expenses_id_seq,expense_changes_id_seq FROM authenticated;
    END IF;
END $$;
COMMIT;
