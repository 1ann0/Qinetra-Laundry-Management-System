-- Keep an owner-attributed before/after record for stage fixes and cancellation.
BEGIN;

CREATE TABLE IF NOT EXISTS order_corrections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    action VARCHAR(20) NOT NULL,
    before_state JSON NOT NULL,
    after_state JSON NOT NULL,
    reason VARCHAR(300) NOT NULL,
    goods_returned_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    still_in_shop_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    request_key VARCHAR(36) UNIQUE,
    request_hash VARCHAR(64),
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT order_correction_action CHECK (action IN ('stage_back', 'cancel'))
);

CREATE INDEX IF NOT EXISTS order_corrections_order_id_idx ON order_corrections(order_id);
ALTER TABLE order_corrections ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON order_corrections FROM PUBLIC;
REVOKE ALL ON SEQUENCE order_corrections_id_seq FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON order_corrections FROM anon;
        REVOKE ALL ON SEQUENCE order_corrections_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON order_corrections FROM authenticated;
        REVOKE ALL ON SEQUENCE order_corrections_id_seq FROM authenticated;
    END IF;
END $$;

COMMIT;
