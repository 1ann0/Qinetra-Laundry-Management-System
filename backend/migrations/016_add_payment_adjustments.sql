-- Corrects a mistaken payment entry or records money actually returned.
BEGIN;

CREATE TABLE IF NOT EXISTS payment_adjustments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    payment_id INTEGER NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
    kind VARCHAR(20) NOT NULL,
    refund_method VARCHAR(20),
    amount NUMERIC(10, 2) NOT NULL,
    reason VARCHAR(300) NOT NULL,
    effective_date DATE NOT NULL,
    request_key VARCHAR(36) UNIQUE,
    request_hash VARCHAR(64),
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT payment_adjustment_positive CHECK (amount > 0),
    CONSTRAINT payment_adjustment_kind CHECK (kind IN ('entry_error', 'refund')),
    CONSTRAINT payment_adjustment_refund_method CHECK (
        (kind = 'entry_error' AND refund_method IS NULL)
        OR (kind = 'refund' AND refund_method IN ('cash', 'mpesa'))
    )
);

CREATE INDEX IF NOT EXISTS payment_adjustments_order_id_idx
ON payment_adjustments(order_id);
CREATE INDEX IF NOT EXISTS payment_adjustments_payment_id_idx
ON payment_adjustments(payment_id);
CREATE INDEX IF NOT EXISTS payment_adjustments_effective_date_idx
ON payment_adjustments(effective_date);

ALTER TABLE payment_adjustments ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON payment_adjustments FROM PUBLIC;
REVOKE ALL ON SEQUENCE payment_adjustments_id_seq FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON payment_adjustments FROM anon;
        REVOKE ALL ON SEQUENCE payment_adjustments_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON payment_adjustments FROM authenticated;
        REVOKE ALL ON SEQUENCE payment_adjustments_id_seq FROM authenticated;
    END IF;
END $$;

COMMIT;
