-- Separate cash movements and immutable Owner confirmations; no old ledger changes.
BEGIN;
CREATE TABLE IF NOT EXISTS till_movements (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_date DATE NOT NULL,
    kind VARCHAR(20) NOT NULL CONSTRAINT till_movement_kind CHECK (kind IN ('addition','withdrawal')),
    amount NUMERIC(12,2) NOT NULL CONSTRAINT till_movement_positive CHECK (amount > 0),
    reference VARCHAR(100) NOT NULL DEFAULT '',
    note VARCHAR(1000) NOT NULL DEFAULT '',
    is_voided BOOLEAN NOT NULL DEFAULT FALSE,
    revision INTEGER NOT NULL DEFAULT 0 CONSTRAINT till_movement_revision CHECK (revision >= 0),
    request_key VARCHAR(36) UNIQUE NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_till_movements_movement_date ON till_movements(movement_date);
CREATE TABLE IF NOT EXISTS till_movement_changes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_id INTEGER NOT NULL REFERENCES till_movements(id) ON DELETE RESTRICT,
    before_details JSONB,
    after_details JSONB NOT NULL,
    reason VARCHAR(200) NOT NULL,
    revision INTEGER NOT NULL CHECK (revision >= 0),
    request_key VARCHAR(36) UNIQUE NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT till_change_revision UNIQUE(movement_id,revision)
);
CREATE TABLE IF NOT EXISTS daily_closes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE NOT NULL,
    revision INTEGER NOT NULL CONSTRAINT daily_close_positive_revision CHECK (revision > 0),
    source_fingerprint VARCHAR(64) NOT NULL,
    snapshot JSONB NOT NULL,
    reason VARCHAR(200) NOT NULL DEFAULT '',
    request_key VARCHAR(36) UNIQUE NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT daily_close_revision UNIQUE(business_date,revision)
);
CREATE INDEX IF NOT EXISTS ix_daily_closes_business_date ON daily_closes(business_date);
ALTER TABLE till_movements ENABLE ROW LEVEL SECURITY;
ALTER TABLE till_movement_changes ENABLE ROW LEVEL SECURITY;
ALTER TABLE daily_closes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON till_movements,till_movement_changes,daily_closes FROM PUBLIC;
REVOKE ALL ON SEQUENCE till_movements_id_seq,till_movement_changes_id_seq,daily_closes_id_seq FROM PUBLIC;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
        REVOKE ALL ON till_movements,till_movement_changes,daily_closes FROM anon;
        REVOKE ALL ON SEQUENCE till_movements_id_seq,till_movement_changes_id_seq,daily_closes_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN
        REVOKE ALL ON till_movements,till_movement_changes,daily_closes FROM authenticated;
        REVOKE ALL ON SEQUENCE till_movements_id_seq,till_movement_changes_id_seq,daily_closes_id_seq FROM authenticated;
    END IF;
END $$;
COMMIT;
