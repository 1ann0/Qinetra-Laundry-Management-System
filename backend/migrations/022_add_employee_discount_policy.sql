-- Default to no employee discount. Runtime access remains through FastAPI only.
BEGIN;

CREATE TABLE IF NOT EXISTS discount_policies (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    employee_max_discount_percent NUMERIC(5, 2) NOT NULL DEFAULT 0
        CHECK (employee_max_discount_percent >= 0 AND employee_max_discount_percent <= 100),
    revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0),
    updated_at TIMESTAMPTZ
);

INSERT INTO discount_policies (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS discount_policy_changes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id INTEGER NOT NULL REFERENCES discount_policies(id) ON DELETE RESTRICT,
    before_percent NUMERIC(5, 2) NOT NULL,
    after_percent NUMERIC(5, 2) NOT NULL,
    revision INTEGER NOT NULL,
    request_key VARCHAR(36) UNIQUE NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    confirmed_by_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    confirmed_by_username VARCHAR(50) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE discount_policies ENABLE ROW LEVEL SECURITY;
ALTER TABLE discount_policy_changes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON discount_policies, discount_policy_changes FROM PUBLIC;
REVOKE ALL ON SEQUENCE discount_policy_changes_id_seq FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON discount_policies, discount_policy_changes FROM anon;
        REVOKE ALL ON SEQUENCE discount_policy_changes_id_seq FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON discount_policies, discount_policy_changes FROM authenticated;
        REVOKE ALL ON SEQUENCE discount_policy_changes_id_seq FROM authenticated;
    END IF;
END $$;

COMMIT;
